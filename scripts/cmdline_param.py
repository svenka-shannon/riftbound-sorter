#!/usr/bin/env python3
"""
Idempotently set a kernel command-line parameter in the Raspberry Pi's
cmdline.txt (used by scripts/setup.sh; standard library only, run as root).

  cmdline_param.py pinctrl_bcm2835.persist_gpio_outputs=0 [--file PATH]

Location: /boot/firmware/cmdline.txt (Bookworm, trixie) or /boot/cmdline.txt
(older images). On Bookworm /boot/cmdline.txt may still exist as a stub that
says "DO NOT EDIT THIS FILE" — it is skipped. cmdline.txt is ONE line: any
existing `name=...` token is replaced, the new one appended, everything else
kept in order; the file is only rewritten if it changes (a copy of the
original is kept as cmdline.txt.riftbound.bak the first time). Prints
"unchanged" or "updated <path>"; a reboot applies it.

Durability: cmdline.txt lives on the FAT boot partition, where a power cut
after a rename that is not yet on disk can leave an empty or missing file
(an unbootable Pi). The new text (and the backup) are written to a temp file
that is fsynced, renamed over the original, and then the directory is
fsynced too, so either the old or the new file is on disk, complete.

Parameter name: the pinctrl-bcm2835 driver declares
`module_param(persist_gpio_outputs, bool, 0444)` (drivers/pinctrl/bcm/
pinctrl-bcm2835.c, Raspberry Pi kernel), so on the command line it is
`pinctrl_bcm2835.persist_gpio_outputs=0` (module name with "_").
"""

import argparse
import os
import shutil
import sys
from pathlib import Path

CANDIDATES = (Path("/boot/firmware/cmdline.txt"), Path("/boot/cmdline.txt"))


def find_cmdline(candidates=CANDIDATES):
    for p in candidates:
        try:
            text = p.read_text()
        except OSError:
            continue
        if "DO NOT EDIT" in text:
            continue
        return p
    return None


def updated(text: str, param: str) -> str:
    name = param.split("=", 1)[0]
    tokens = [t for t in text.split() if t.split("=", 1)[0] != name]
    tokens.append(param)
    return " ".join(tokens) + "\n"


def fsync_dir(directory: Path) -> None:
    """fsync a directory so a rename in it is on disk (best effort: some
    filesystems / platforms refuse to open a directory for fsync)."""
    try:
        fd = os.open(directory, os.O_RDONLY)
    except OSError:
        return
    try:
        os.fsync(fd)
    except OSError:
        pass
    finally:
        os.close(fd)


def write_durably(path: Path, data: bytes) -> None:
    """Write `data` to a temp file next to `path`, fsync it, rename it over
    `path`, fsync the directory."""
    tmp = path.with_name(path.name + ".tmp")
    with open(tmp, "wb") as fh:
        fh.write(data)
        fh.flush()
        os.fsync(fh.fileno())
    os.replace(tmp, path)
    fsync_dir(path.parent)


def ensure_param(path: Path, param: str) -> bool:
    """True if the file was changed."""
    raw = path.read_bytes()
    text = raw.decode()
    new = updated(text, param)
    if new.split() == text.split():
        return False
    backup = path.with_name(path.name + ".riftbound.bak")
    if not backup.exists():
        write_durably(backup, raw)
        shutil.copystat(path, backup)
    write_durably(path, new.encode())
    return True


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="set a kernel cmdline parameter idempotently")
    ap.add_argument("param", help="name=value")
    ap.add_argument("--file", type=Path, help="cmdline.txt to edit (default: auto-detect)")
    args = ap.parse_args(argv)
    if "=" not in args.param:
        ap.error("param must be name=value")
    path = args.file or find_cmdline()
    if path is None:
        print("cmdline.txt not found in " + ", ".join(map(str, CANDIDATES)), file=sys.stderr)
        return 1
    print(f"updated {path}" if ensure_param(path, args.param) else "unchanged")
    return 0


if __name__ == "__main__":
    sys.exit(main())
